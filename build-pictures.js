#!/usr/bin/env node
'use strict';

/**
 * Packs every image in ./pictures and ./samples into pictures.js as data URIs, so
 * the explorer works when index.html is opened straight from disk (file://).
 * Browsers refuse to use files next to a file:// page as WebGL textures, but
 * data URIs are allowed.
 *
 * Run it again whenever you add, remove or change a photo:
 *     node build-pictures.js
 */

const fs = require('fs');
const path = require('path');

const DIRS = ['pictures', 'samples']; // every image in these folders is embedded
const OUT = 'pictures.js';
const TYPES = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };

const root = __dirname;
const files = DIRS.flatMap((dir) => {
    const folder = path.join(root, dir);
    if (!fs.existsSync(folder)) return [];
    return fs.readdirSync(folder)
        .filter((name) => TYPES[path.extname(name).toLowerCase()])
        .sort()
        .map((name) => `${dir}/${name}`);
});

if (files.length === 0) {
    console.error(`No images found in ${DIRS.map((d) => `./${d}`).join(' or ')}`);
    process.exit(1);
}

let total = 0;
const entries = files.map((file) => {
    const bytes = fs.readFileSync(path.join(root, file));
    total += bytes.length;
    const type = TYPES[path.extname(file).toLowerCase()];
    return `    ${JSON.stringify(file)}: "data:${type};base64,${bytes.toString('base64')}"`;
});

const header = `/* Generated by build-pictures.js. Do not edit; re-run "node build-pictures.js". */\n`;
fs.writeFileSync(path.join(root, OUT), `${header}window.EmbeddedPhotos = {\n${entries.join(',\n')}\n};\n`);

console.log(`Wrote ${OUT}: ${files.length} image(s), ${(total / 1048576).toFixed(1)} MB of photos`);
files.forEach((file) => console.log(`  ${file}`));
